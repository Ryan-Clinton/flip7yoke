// Builds dist\Flip7yoke-server.exe: a Node single executable application (SEA) with the game inside.
//   node tools/build.js
// Steps: check the Node version, bundle our modules into one script, list the page files as SEA assets,
// make the SEA blob, copy node.exe, inject the blob with postject, then start the exe once as a smoke test.
// A SEA can only require Node's built-in modules and can't read files beside itself, hence the bundle and assets.
const fs = require('fs');
const path = require('path');
const net = require('net');
const { execFileSync, spawn } = require('child_process');

const ROOT = path.join(__dirname, '..');
const BUILD = path.join(ROOT, 'build');
const DIST = path.join(ROOT, 'dist');
const EXE = path.join(DIST, 'Flip7yoke-server.exe');
const step = s => console.log(`\n== ${s}`);
const fail = s => { console.error(`\nBUILD FAILED: ${s}`); process.exit(1); };

// 1. Node version. A SEA blob only works with the exact node.exe it is injected into.
step('Node version');
const want = fs.readFileSync(path.join(ROOT, '.node-version'), 'utf8').trim();
if (process.version !== `v${want}`) fail(`this build needs Node ${want} (.node-version); this is ${process.version}`);
console.log(process.version);

// 2. Bundle. Each module becomes a function in a table; require() of a relative path looks it up there, anything
// else goes to Node's own require (built-ins only, in a SEA). rules.js is included byte for byte.
step('Bundle');
const MODULES = ['main.js', 'server.js', 'package.json', 'public/rules.js',
  ...fs.readdirSync(path.join(ROOT, 'lib')).filter(f => f.endsWith('.js')).map(f => `lib/${f}`)];
const sources = {};
for (const m of MODULES) sources[m] = fs.readFileSync(path.join(ROOT, m), 'utf8');
const pkg = JSON.parse(sources['package.json']);
// Every local require must be one of the bundled modules, or the exe would fail at run time.
for (const [m, src] of Object.entries(sources)) {
  for (const [, id] of src.matchAll(/require\(['"](\.{1,2}\/[^'"]+)['"]\)/g)) {
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(m), id));
    if (!sources[target] && !sources[target + '.js']) fail(`${m} requires ${id}, which isn't in the bundle`);
  }
}
const table = Object.entries(sources).map(([m, src]) => m.endsWith('.json')
  ? `${JSON.stringify(m)}: function (module) { module.exports = ${src.trim()}; }`
  : `${JSON.stringify(m)}: function (module, exports, require, __filename, __dirname) {\n${src}\n}`).join(',\n');
const bundle = `// Flip7yoke ${pkg.version}: generated by tools/build.js, do not edit.
'use strict';
const __path = require('path');
const __modules = {
${table}
};
const __cache = {};
function __load(name) {
  if (__cache[name]) return __cache[name].exports;
  const module = { exports: {} };
  __cache[name] = module;
  const dir = __path.posix.dirname(name);
  const req = id => {
    if (!id.startsWith('.')) return require(id);
    const t = __path.posix.normalize(__path.posix.join(dir, id));
    return __load(__modules[t] ? t : t + '.js');
  };
  const virtualDir = __path.join(__path.dirname(process.execPath), dir);
  __modules[name].call(module.exports, module, module.exports, req, __path.join(virtualDir, __path.posix.basename(name)), virtualDir);
  return module.exports;
}
__load('main.js');
`;
fs.rmSync(BUILD, { recursive: true, force: true });
fs.mkdirSync(BUILD, { recursive: true });
fs.writeFileSync(path.join(BUILD, 'bundle.js'), bundle);
console.log(`${MODULES.length} modules, ${(bundle.length / 1024).toFixed(0)} KB`);

// 3. Assets: every file in public/, plus a manifest listing them (replaces reading the folder at run time).
step('Assets');
const files = [];
const walk = rel => {
  for (const e of fs.readdirSync(path.join(ROOT, 'public', rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) walk(r); else files.push(r);
  }
};
walk('');
fs.writeFileSync(path.join(BUILD, 'manifest.json'), JSON.stringify(files));
const assets = { 'manifest.json': path.join(BUILD, 'manifest.json') };
for (const f of files) assets[`public/${f}`] = path.join(ROOT, 'public', f);
// Same scoring everywhere: the browser's /rules.js asset and the copy inside the bundle must be identical.
if (!bundle.includes(fs.readFileSync(path.join(ROOT, 'public', 'rules.js'), 'utf8'))) fail('the bundled rules.js differs from public/rules.js');
console.log(`${files.length} files: ${files.join(', ')}`);

// 4. SEA blob.
step('SEA blob');
const seaConfig = {
  main: path.join(BUILD, 'bundle.js'), output: path.join(BUILD, 'sea-prep.blob'),
  disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false, assets,
};
fs.writeFileSync(path.join(BUILD, 'sea-config.json'), JSON.stringify(seaConfig, null, 2));
execFileSync(process.execPath, ['--experimental-sea-config', path.join(BUILD, 'sea-config.json')], { stdio: 'inherit' });

// 5. Copy node.exe. Its Authenticode signature becomes invalid once the blob is injected; Windows still runs it.
// signtool (Windows SDK) removes it cleanly when installed; without it the stale signature is left, which is harmless.
step('Copy node.exe');
fs.mkdirSync(DIST, { recursive: true });
fs.copyFileSync(process.execPath, EXE);
try {
  execFileSync('signtool', ['remove', '/s', EXE], { stdio: 'pipe' });
  console.log('removed the Node.js signature');
} catch { console.log('signtool not found; leaving the old signature (harmless)'); }

// 6. Inject the blob.
step('Inject');
const postject = path.join(ROOT, 'node_modules', 'postject', 'dist', 'cli.js');
if (!fs.existsSync(postject)) fail('postject is missing: run npm install');
execFileSync(process.execPath, [postject, EXE, 'NODE_SEA_BLOB', path.join(BUILD, 'sea-prep.blob'),
  '--sentinel-fuse', 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2'], { stdio: 'inherit' });

// 7. Smoke test: --version, then start it on a spare port with a throwaway data folder, check it answers, stop it.
step('Smoke test');
const v = execFileSync(EXE, ['--version'], { encoding: 'utf8' }).trim();
if (v !== pkg.version) fail(`--version said ${JSON.stringify(v)}, expected ${pkg.version}`);
console.log(`--version: ${v}`);
(async () => {
  const port = await new Promise(r => { const s = net.createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => r(p)); }); });
  const data = path.join(BUILD, 'smoke-data');
  fs.mkdirSync(data, { recursive: true });
  const env = { ...process.env, FLIP7_DATA: data, PORT: String(port), ALSO_PORT: '0', FLIP7_NO_READER: '1' };
  for (const k of ['STATE_FILE', 'HISTORY_FILE', 'SCANS_DIR']) delete env[k];
  const p = spawn(EXE, [], { env, stdio: 'ignore', windowsHide: true });
  const exited = new Promise(r => p.once('exit', r));
  let st = null;
  for (let i = 0; i < 100 && !st; i++) {
    await new Promise(r => setTimeout(r, 100));
    st = await fetch(`http://127.0.0.1:${port}/api/status`).then(r => r.json()).catch(() => null);
  }
  const page = st && await fetch(`http://127.0.0.1:${port}/board`).then(r => r.text()).catch(() => '');
  const rec = JSON.parse(fs.readFileSync(path.join(data, 'server.pid.json'), 'utf8'));
  const stop = await fetch(`http://127.0.0.1:${rec.controlPort}/stop`, { method: 'POST', headers: { 'x-flip7-token': rec.token } }).then(r => r.json()).catch(e => ({ error: e.message }));
  const code = await exited;
  if (!st) fail('the exe started but never answered /api/status');
  if (st.token !== rec.token) fail('the server on the port is not the one the exe started');
  if (!page.includes('Flip<span class="seven">7</span>yoke')) fail('the exe did not serve the page');
  if (!stop.saved || code !== 0) fail(`stop failed: ${JSON.stringify(stop)}, exit code ${code}`);
  fs.rmSync(data, { recursive: true, force: true });
  const mb = (fs.statSync(EXE).size / 1048576).toFixed(0);
  console.log(`answered, served the page, stopped cleanly\n\nBuilt ${path.relative(ROOT, EXE)} (${mb} MB), version ${pkg.version}`);
})();
